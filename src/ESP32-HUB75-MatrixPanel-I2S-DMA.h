    void transform(int16_t &x, int16_t &y, int16_t &w, int16_t &h) {
#ifndef NO_GFX
        int16_t t;
        switch (rotation) {
        case 1:
            t = _height - 1 - y - (h - 1);
            y = x;
            x = t;
            t = h;
            h = w;
            w = t;
            return;
        case 2:
            x = _width - 1 - x - (w - 1);
            y = _height - 1 - y - (h - 1);
            return;
        case 3:
            t = y;
            y = _width - 1 - x - (w - 1);
            x = t;
            t = h;
            h = w;
            w = t;
            return;
        }
#endif
    }

