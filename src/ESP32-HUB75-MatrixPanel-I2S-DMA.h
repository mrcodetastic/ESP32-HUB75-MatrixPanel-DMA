/**
 * Custom memory deleter for ESP32 heap capabilities (e.g. DMA, SPIRAM).
 */
struct HeapCapsDeleter {
    void operator()(void* ptr) const {
        if (ptr) {
            heap_caps_free(ptr);
        }
    }
};

template <typename T>
using dma_unique_ptr = std::unique_ptr<T[], HeapCapsDeleter>;


/** 
 * @struct rowBitStruct
 * @brief Raw DMA data structure driving TWO full pixel rows across chained modules.
 *
 * @var width Width of the row in pixels
 * @var colour_depth Bit depth layers (copies of each row per color bitplane)
 * @var data Pointer to DMA memory array holding pixel color payload
 * 
 * @note Memory alignment varies by target device and configuration:
 * - ESP32-S3 with SPIRAM: Word-aligned block allocated in SPIRAM
 * - Default targets: Allocated in DMA-capable internal RAM
 */
struct rowBitStruct {
    const size_t width;
    const uint8_t colour_depth;
    dma_unique_ptr<ESP32_I2S_DMA_STORAGE_TYPE> data;

    /** 
     * @brief Calculates DMA row data array memory requirements in bytes.
     * @param single_color_depth If true, returns size for 1 bitplane layer; if false, for all layers.
     */
    [[nodiscard]] size_t getColorDepthSize(bool single_color_depth) const noexcept {
        int _cdepth = single_color_depth ? 1 : colour_depth;
        return width * _cdepth * sizeof(ESP32_I2S_DMA_STORAGE_TYPE);
    }

    /** 
     * @brief Returns a pointer to the row data vector starting at pixel[0] for a specific color bitplane depth.
     */
    [[nodiscard]] inline ESP32_I2S_DMA_STORAGE_TYPE* getDataPtr(const uint8_t depth = 0) const noexcept { 
        return &(data[depth * width]); 
    }

    // Constructor: Allocates DMA-capable memory block for struct storage
    rowBitStruct(const size_t _width, const uint8_t _depth) 
        : width(_width), colour_depth(_depth), data(nullptr)
    {
        size_t bytes = getColorDepthSize(false);
#if defined(SPIRAM_DMA_BUFFER)
        auto* raw_ptr = static_cast<ESP32_I2S_DMA_STORAGE_TYPE*>(
            heap_caps_aligned_alloc(64, bytes, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT));
#else
        auto* raw_ptr = static_cast<ESP32_I2S_DMA_STORAGE_TYPE*>(
            heap_caps_malloc(bytes, MALLOC_CAP_INTERNAL | MALLOC_CAP_DMA));
#endif
        data.reset(raw_ptr);
    }

    ~rowBitStruct() = default;

    // Explicit non-copyable semantic contract (Rule of Five)
    rowBitStruct(const rowBitStruct&) = delete;
    rowBitStruct& operator=(const rowBitStruct&) = delete;

    rowBitStruct(rowBitStruct&&) noexcept = default;
    rowBitStruct& operator=(rowBitStruct&&) noexcept = default;
};

/**
 * @struct frameStruct
 * @brief Holds full-frame data across parallel sub-rows.
 *
 * @note Managed row-by-row via individual rowBits pointers.
 */
struct frameStruct {
    uint8_t rows = 0; // Active row count in current frame
    std::vector<std::unique_ptr<rowBitStruct>> rowBits;
};

